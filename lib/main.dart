import 'package:flutter/material.dart';
import 'package:flutter_web_plugins/url_strategy.dart';
import 'package:firebase_core/firebase_core.dart';
import 'firebase_options.dart'; // Generated by flutterfire configure
import 'models/user_model.dart';
import 'services/json_storage_service.dart';
import 'screens/auth_screen.dart';
import 'screens/dashboard_screen.dart';
import 'theme/app_theme.dart';
import 'widgets/mafia_logo.dart';

void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  usePathUrlStrategy();

  // Initialize Firebase Cloud Service
  await Firebase.initializeApp(
    options: DefaultFirebaseOptions.currentPlatform,
  );

  runApp(const MyApp());
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Mafia Quiz | Information Sciences Mixer 2026',
      debugShowCheckedModeBanner: false,
      theme: buildNoirTheme(),
      home: const RootSessionWrapper(),
    );
  }
}

class RootSessionWrapper extends StatefulWidget {
  const RootSessionWrapper({super.key});

  @override
  State<RootSessionWrapper> createState() => _RootSessionWrapperState();
}

class _RootSessionWrapperState extends State<RootSessionWrapper> {
  bool _isLoading = true;
  User? _currentUser;

  @override
  void initState() {
    super.initState();
    _checkExistingSession();
  }

  Future<void> _checkExistingSession() async {
    final user = await JsonStorageService.getActiveSessionUser();
    if (!mounted) return;
    setState(() {
      _currentUser = user;
      _isLoading = false;
    });
  }

  @override
  Widget build(BuildContext context) {
    if (_isLoading) {
      return const Scaffold(
        body: NoirBackground(
          child: Center(
            child: Column(
              mainAxisSize: MainAxisSize.min,
              children: [
                FedoraLogo(size: 72, color: NoirColors.gold),
                SizedBox(height: 24),
                SizedBox(
                  width: 26,
                  height: 26,
                  child: CircularProgressIndicator(
                    strokeWidth: 2,
                    color: NoirColors.gold,
                  ),
                ),
              ],
            ),
          ),
        ),
      );
    }

    if (_currentUser != null) {
      return GameDashboardScreen(
        user: _currentUser!,
        onLogout: () => setState(() => _currentUser = null),
      );
    }

    return AuthScreen(
      onLoginSuccess: (user) => setState(() => _currentUser = user),
    );
  }
}